import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/**
 * Compile design tokens into the Tailwind theme.
 *
 * Tailwind v4 is configured in CSS, so the output is a `@theme` block of custom properties. The
 * point of generating it is that design owns `tokens/design-tokens.json` and nothing in the
 * component layer is allowed to invent a value: if a colour isn't a token, there's no utility for
 * it. Re-exporting from Figma and re-running this is the whole update path.
 */

type Token = { $value: string };
type TokenGroup = { [key: string]: Token | TokenGroup | string };

const root = resolve(import.meta.dirname, '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/design-tokens.json'), 'utf8')) as TokenGroup;

const isToken = (node: unknown): node is Token =>
  typeof node === 'object' && node !== null && '$value' in node;

/** Flatten nested groups into `prefix-path-to-leaf` custom property names. */
function flatten(group: TokenGroup, path: string[] = []): Array<[string, string]> {
  const out: Array<[string, string]> = [];

  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    if (isToken(node)) {
      out.push([[...path, key].join('-'), node.$value]);
    } else if (typeof node === 'object') {
      out.push(...flatten(node, [...path, key]));
    }
  }

  return out;
}

// Tailwind v4 derives utility names from the custom property namespace: --color-* produces
// bg-*/text-*/border-*, --text-* produces font sizes, and so on. The token file's top-level keys
// are named to line up with those namespaces, so the mapping is one-to-one.
const NAMESPACES = ['color', 'font', 'text', 'radius', 'shadow'] as const;

const lines = NAMESPACES.flatMap((namespace) => {
  const group = tokens[namespace];
  if (!group || typeof group !== 'object') return [];

  const prefix = namespace === 'radius' ? 'radius' : namespace;
  return [
    `  /* ${namespace} */`,
    ...flatten(group as TokenGroup).map(([name, value]) => `  --${prefix}-${name}: ${value};`),
    ''
  ];
});

const css = `/* Generated by \`npm run tokens\` from tokens/design-tokens.json. Do not edit by hand. */
@theme {
${lines.join('\n')}}
`;

writeFileSync(resolve(root, 'src/app/tokens.css'), css);

const count = NAMESPACES.reduce(
  (n, ns) => n + (typeof tokens[ns] === 'object' ? flatten(tokens[ns] as TokenGroup).length : 0),
  0
);
console.log(`Wrote src/app/tokens.css — ${count} tokens across ${NAMESPACES.length} namespaces.`);
